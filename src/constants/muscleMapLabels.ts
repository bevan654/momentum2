/** Display name for a region slug (unsided). Falls back to the slug in title case. */
export function regionLabel(slug: string): string {
  return REGION_LABELS[slug] ?? slug.split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}
